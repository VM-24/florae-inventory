// A code must not appear twice — upsert by sku would silently merge the rows.
function assertUniqueCodes() {
  const seen = new Map<string, string>();
  for (const sheet of SHEETS) {
    for (const [sku, name] of sheet.rows) {
      if (sku === null) continue;
      const prev = seen.get(sku);
      if (prev) throw new Error(`Duplicate code ${sku}: "${prev}" and "${name}" (${sheet.warehouse})`);
      seen.set(sku, name);
    }
  }
}

async function main() {
  assertUniqueCodes();
  for (const [index, sheet] of SHEETS.entries()) {
    const category = await prisma.category.upsert({
      where: { name: sheet.warehouse },
      update: {},
      create: { name: sheet.warehouse, sortOrder: (index + 1) * 10 },
    });
    for (const [sku, name, unit, description] of sheet.rows) {
      const data = { sku, name, unit, description: description ?? null, categoryId: category.id };
      if (sku !== null) {
        await prisma.item.upsert({ where: { sku }, update: {}, create: data });
        continue;
      }
      // No code in the sheet: match by name within the warehouse.
      const existing = await prisma.item.findFirst({ where: { categoryId: category.id, name } });
      if (!existing) await prisma.item.create({ data });
    }
    console.log(`🌱 ${sheet.warehouse} (${sheet.date}): ${sheet.rows.length} items`);
  }
}

main()
  .catch(err => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
