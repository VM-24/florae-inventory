async function main() {
  let items = 0;
  for (const [index, section] of SHEET.entries()) {
    const category = await prisma.category.upsert({
      where: { name: section.category },
      update: {},
      create: { name: section.category, sortOrder: (index + 1) * 10 },
    });

    for (const [name, openingQty, currentQty, shortageQty = 0, note, unit] of section.rows) {
      const item = await prisma.item.upsert({
        where: { categoryId_name: { categoryId: category.id, name } },
        update: {},
        create: { categoryId: category.id, name, unit: unit ?? 'шт', openingQty },
      });
      await prisma.monthlyCount.upsert({
        where: { itemId_month: { itemId: item.id, month: COUNT_MONTH } },
        update: {},
        create: { itemId: item.id, month: COUNT_MONTH, currentQty, shortageQty, note: note ?? null },
      });
      items++;
    }
  }
  console.log(`🌱 Seeded ${SHEET.length} categories, ${items} items`);
}

main()
  .catch(err => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
