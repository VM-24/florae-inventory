import { Router } from 'express';
import bcrypt from 'bcryptjs';
import { z } from 'zod';
import { prisma } from '../db';
import { asyncHandler } from '../http/errors';
import { issueToken, requirePermission } from './middleware';
import { CURRENCY } from '../config';
import { PERMISSION_GROUPS } from './permissions';
import {
  changeOwnPassword, createRole, createUserWithIssuedPassword, deleteRole, listRoles, listUsers,
  resetPassword, updateRole, updateUser,
} from './users';

const loginSchema = z.object({
  login: z.string().trim().toLowerCase().min(1),
  password: z.string().min(1),
});

export const loginRouter = Router();

loginRouter.post('/login', asyncHandler(async (req, res) => {
  const parsed = loginSchema.safeParse(req.body);
  // Same message for "no such login" and "wrong password" — no login enumeration.
  if (!parsed.success) return res.status(401).json({ error: 'Неверный логин или пароль' });

  const user = await prisma.user.findUnique({ where: { login: parsed.data.login } });
  const ok = user && user.active && (await bcrypt.compare(parsed.data.password, user.passwordHash));
  if (!ok) return res.status(401).json({ error: 'Неверный логин или пароль' });

  await prisma.user.update({ where: { id: user.id }, data: { lastLoginAt: new Date() } });
  res.json({ token: issueToken(user.id) });
}));

// Own profile — any authenticated user, also while a password change is pending.
export const meRouter = Router();

meRouter.get('/me', (req, res) => {
  const a = req.auth!;
  res.json({
    login: a.login,
    name: a.name,
    role: { id: a.roleId, name: a.roleName, isOwner: a.isOwner },
    permissions: [...a.permissions].sort(),
    mustChangePassword: a.mustChangePassword,
    currency: CURRENCY,
  });
});

const changePasswordSchema = z.object({ current: z.string().min(1, 'обязательно'), next: z.string() }).strict();

meRouter.post('/me/password', asyncHandler(async (req, res) => {
  const { current, next } = changePasswordSchema.parse(req.body);
  await changeOwnPassword(req.auth!.userId, current, next);
  res.json({ ok: true });
}));

// ------------------------------------------------------------ users & roles

const createUserSchema = z.object({
  login: z.string().trim().toLowerCase().min(1, 'обязательно').max(50)
    .regex(/^[a-z0-9._-]+$/, 'только латиница, цифры, точка, дефис и подчёркивание'),
  name: z.string().trim().min(1, 'обязательно').max(100),
  roleId: z.string().uuid('некорректная роль'),
}).strict();

const updateUserSchema = z.object({
  name: z.string().trim().min(1, 'обязательно').max(100).optional(),
  roleId: z.string().uuid('некорректная роль').optional(),
  active: z.boolean().optional(),
}).strict();

const roleSchema = z.object({
  name: z.string().trim().min(1, 'обязательно').max(60),
  permissions: z.array(z.string()).max(100),
}).strict();

export const userRouter = Router();

// Permission catalog for the role editor.
userRouter.get('/permissions', requirePermission('roles.manage', 'users.manage'), (_req, res) => {
  res.json(PERMISSION_GROUPS);
});

userRouter.get('/users', requirePermission('users.manage'), asyncHandler(async (_req, res) => {
  res.json(await listUsers());
}));

// The start password is generated by the server and returned exactly once.
userRouter.post('/users', requirePermission('users.manage'), asyncHandler(async (req, res) => {
  const input = createUserSchema.parse(req.body);
  res.status(201).json(await createUserWithIssuedPassword(input, req.auth!.userId));
}));

userRouter.patch('/users/:id', requirePermission('users.manage'), asyncHandler(async (req, res) => {
  const patch = updateUserSchema.parse(req.body);
  res.json(await updateUser(req.params.id, patch, req.auth!.userId));
}));

userRouter.post('/users/:id/reset-password', requirePermission('users.manage'), asyncHandler(async (req, res) => {
  res.json({ password: await resetPassword(req.params.id, req.auth!.userId) });
}));

// Roles are listed for both editors: the user form needs them to pick a role.
userRouter.get('/roles', requirePermission('roles.manage', 'users.manage'), asyncHandler(async (_req, res) => {
  res.json(await listRoles());
}));

userRouter.post('/roles', requirePermission('roles.manage'), asyncHandler(async (req, res) => {
  res.status(201).json(await createRole(roleSchema.parse(req.body), req.auth!.userId));
}));

userRouter.patch('/roles/:id', requirePermission('roles.manage'), asyncHandler(async (req, res) => {
  res.json(await updateRole(req.params.id, roleSchema.partial().strict().parse(req.body), req.auth!.userId));
}));

userRouter.delete('/roles/:id', requirePermission('roles.manage'), asyncHandler(async (req, res) => {
  await deleteRole(req.params.id, req.auth!.userId);
  res.status(204).end();
}));
